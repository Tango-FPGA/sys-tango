#!/usr/bin/env bash
# gen.sh -- regenerate ascal_fixed.v, the Verilog netlist of the REAL TEMLIB ascal
# (sys/ascal.vhd, generics fixed by ascal_fixed.vhd), with GHDL's built-in synthesis,
# then prove sys/ascal_wrap.v + ascal_shim.v + the netlist elaborate (verilator
# --lint-only).  Runs no simulation.  ascal_fixed.v is only replaced when both pass.
#
# Needs GHDL >= 4 with --synth (the mcode build is fine) and Verilator 5.  Both steps
# run memory-capped through sys/build_tools/tango_capped.sh (TANGO_MEM_CAP, default 4G).
# A light job (seconds), but run it alone, not beside a Gowin build or a Verilator sim.
#   gen.sh       ascal.vhd + ascal_fixed.vhd (FRAC 4) -> ascal_fixed.v, linted with ascal_shim.v (every build)
#   gen.sh 8     ascal.vhd + ascal_poly_bram.patch (the coefficient memories as block RAM, NOTICE) + ascal_fixed8.vhd
#                (FRAC 8, MiSTer's) -> ascal_fixed8.v, linted with ascal_shim8.v: the TANGO_VIDEO_PROC builds
#                (README "Video and audio processing").  ascal.vhd itself is never modified.
#   gen.sh 4d / 8d  the same with the DDR3 scaler port's Avalon side (N_DW 128, N_AW 28, RAMBASE 0x2000_0000;
#                ascal_fixed{,8}_ddr3.vhd -> ascal_fixed{,8}_ddr3.v, linted with ascal_shim{,8}_ddr3.v): the
#                TANGO_VIDEO_DDR3 builds (README "The DDR3 path").
set -eu
case "${1:-4}" in
    4)  WV=ascal_fixed;       SHIM=ascal_shim.v;       NMIN=6; PATCH="" ;;
    8)  WV=ascal_fixed8;      SHIM=ascal_shim8.v;      NMIN=9; PATCH=ascal_poly_bram.patch ;;
    4d) WV=ascal_fixed_ddr3;  SHIM=ascal_shim_ddr3.v;  NMIN=6; PATCH="" ;;
    8d) WV=ascal_fixed8_ddr3; SHIM=ascal_shim8_ddr3.v; NMIN=9; PATCH=ascal_poly_bram.patch ;;
    *) echo "usage: gen.sh [4|8|4d|8d]" >&2; exit 2 ;;
esac
HERE="$(cd "$(dirname "$0")" && pwd)"
SYS="$(cd "$HERE/.." && pwd)"            # the framework (sys-tango), wherever it is mounted
ROOT="$(dirname "$SYS")"; SYSN="$(basename "$SYS")"   # in a core: <core>/ and "sys"
CAPPED="$SYS/build_tools/tango_capped.sh"
export TANGO_MEM_CAP="${TANGO_MEM_CAP:-4G}"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# ---- 1. GHDL synthesis (VHDL-2008; ascal.vhd needs no -fsynopsys / -frelaxed).
# Relative source paths keep the netlist's source comments checkout-independent.
cd "$ROOT"
SRC="$SYSN/ascal.vhd"
if [ -n "$PATCH" ]; then
    # FRAC 8: the patched copy, under a fixed relative name (sys/ascal_poly_bram.vhd) for reproducible comments
    mkdir -p "$WORK/src/$SYSN/ascal_ghdl"
    cp "$SYSN/ascal.vhd" "$WORK/src/$SYSN/ascal_poly_bram.vhd"
    patch --quiet "$WORK/src/$SYSN/ascal_poly_bram.vhd" "$HERE/$PATCH" || { echo "gen.sh: $PATCH does not apply" >&2; exit 1; }
    cp "$HERE/$WV.vhd" "$WORK/src/$SYSN/ascal_ghdl/"
    cd "$WORK/src"; SRC="$SYSN/ascal_poly_bram.vhd"
fi
GHDL_ARGS=(--std=08 -Wno-hide --out=verilog
           "$SRC" "$SYSN/ascal_ghdl/$WV.vhd" -e $WV)
if ! "$CAPPED" ghdl --synth --workdir="$WORK" "${GHDL_ARGS[@]}" \
        > "$WORK/netlist.v" 2> "$WORK/synth.log"; then
    cat "$WORK/synth.log" >&2
    echo "gen.sh: GHDL synthesis FAILED" >&2; exit 1
fi
grep -E 'warning|note|tango_capped' "$WORK/synth.log" >&2 || true

# The six arrays that must stay RAMs (i_dpram, o_dpram, o_line0..3): as flops, the
# 4 x 2048 x 24 line buffers would make the Verilator build enormous.  FRAC 8: also the three
# coefficient memories (o_h/o_v/o_a_poly_mem, 256 x 40 each), which the patch makes RAMs.
NRAM=$(grep -c 'note: found RAM' "$WORK/synth.log" || true)
[ "$NRAM" -ge $NMIN ] || { echo "gen.sh: only $NRAM RAMs inferred (want $NMIN): memories became flops" >&2; exit 1; }
grep -q "^module $WV\$" "$WORK/netlist.v" || { echo "gen.sh: no module $WV in the netlist" >&2; exit 1; }
if grep -Eq '^module ascal( |\(|$)' "$WORK/netlist.v"; then
    echo "gen.sh: the netlist defines module ascal, which clashes with ascal_shim.v" >&2; exit 1
fi

cd "$ROOT"                               # (FRAC 8 ran GHDL in $WORK/src)
{
    if [ -z "$PATCH" ]; then
    echo "// $WV.v -- GENERATED by $SYSN/ascal_ghdl/gen.sh ${1:-4}; do not edit."
    echo "// GHDL synthesis of sys/ascal.vhd (TEMLIB AVALON SCALER) with the generics fixed in"
    echo "// $SYSN/ascal_ghdl/$WV.vhd.  Use with $SHIM in place of ascal.vhd."
    else
    echo "// $WV.v -- GENERATED by $SYSN/ascal_ghdl/gen.sh ${1:-4}; do not edit."
    echo "// GHDL synthesis of sys/ascal.vhd (TEMLIB AVALON SCALER) patched with $SYSN/ascal_ghdl/$PATCH"
    echo "// (the coefficient memories as block RAM; the patched copy is named ascal_poly_bram.vhd below), with"
    echo "// the generics fixed in $SYSN/ascal_ghdl/$WV.vhd (FRAC 8).  Use with $SHIM in place of ascal.vhd."
    fi
    echo "// A translation of ascal.vhd, under ascal.vhd's terms (NOTICE); its header:"
    sed -n '1,9p' "$SYSN/ascal.vhd" | sed 's#^--#//#'
    echo "// $(ghdl --version | head -1)"
    echo "// ghdl --synth ${GHDL_ARGS[*]}"
    echo "// sha256 $(sha256sum "$SYSN/ascal.vhd")"
    [ -n "$PATCH" ] && echo "// sha256 $(sha256sum "$SYSN/ascal_ghdl/$PATCH")"
    echo "// sha256 $(sha256sum "$SYSN/ascal_ghdl/$WV.vhd")"
    cat "$WORK/netlist.v"
} > "$WORK/$WV.v"

# ---- 2. Elaboration proof: ascal_wrap.v UNMODIFIED + shim + netlist.
# -GRAMBASE states what tango_sys passes (tango_cfg.vh TANGO_VIDEO_ASCAL_RAMBASE = 32'h0140_0000,
# also ascal_wrap's default), which the netlist bakes in.
# Expected warnings, all from ascal_wrap.v: PINMISSING pal1_dr/pal2_dr (left unconnected)
# and WIDTHEXPAND vmin/vmax (11-bit wires on 12-bit ports, zero-extended).
# FRAC 8: ascal_wrap.v as a TANGO_VIDEO_PROC build compiles it (its poly port, FRAC 8 via tango_cfg.vh).
LDEF=""; [ -n "$PATCH" ] && LDEF="-DTANGO_VIDEO_PROC -I$SYS"
RB="32'h01400000"
case "$WV" in *_ddr3) LDEF="$LDEF -DTANGO_VIDEO_DDR3"; RB="32'h20000000";; esac
cd "$WORK"
"$CAPPED" verilator --lint-only -Wno-fatal $LDEF --top-module ascal_wrap -GRAMBASE="$RB" \
    "$SYS/ascal_wrap.v" "$HERE/$SHIM" "$WORK/$WV.v"

mv "$WORK/$WV.v" "$HERE/$WV.v"
echo "gen.sh: wrote $HERE/$WV.v ($(wc -l < "$HERE/$WV.v") lines, $NRAM RAMs); lint PASS"
